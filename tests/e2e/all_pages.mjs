const app = async (action_id, arguments_ = {}, confirm = false) => {
  const receipt = await api('POST', '/api/app', { session_id: state.session, operation: 'execute', action_id, arguments: arguments_, request_id: `${phase}-${action_id}-${state.request = (state.request ?? 0) + 1}` })
  if (receipt.status === 'confirmation_required') {
    assert(confirm, `${action_id} unexpectedly required confirmation`)
    const result = await api('POST', '/api/app/confirm', { session_id: state.session, confirmation_id: receipt.confirmation_id })
    assert(result.ok && result.verification.passed, JSON.stringify(result))
    report.app_receipts.push(result)
    return result
  }
  assert(receipt.ok && receipt.verification.passed, JSON.stringify(receipt))
  report.app_receipts.push(receipt)
  return receipt
}
