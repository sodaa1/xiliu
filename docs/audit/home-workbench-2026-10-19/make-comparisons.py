from pathlib import Path
from PIL import Image,ImageDraw
root=Path('docs/audit/home-workbench-2026-10-19')
ref=Path('tmp/ui-reference-20261019/Xiliu_高清页面参考图/主页')
def board(a,b,path,labels):
    h=max(a.height,b.height)
    result=Image.new('RGB',(a.width+b.width,h+40),'#f0eef6')
    result.paste(a,(0,40));result.paste(b,(a.width,40))
    draw=ImageDraw.Draw(result);draw.text((16,12),labels[0],fill='#302448');draw.text((a.width+16,12),labels[1],fill='#302448')
    result.save(root/path)
source=Image.open(ref/'01-home-main.jpg').convert('RGB').resize((1440,884),Image.Resampling.LANCZOS)
actual=Image.open(root/'after-desktop.png').convert('RGB')
